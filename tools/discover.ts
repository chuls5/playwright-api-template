/**
 * W1 discovery: OpenAPI 3 → targets/<t>/map/catalog.json + graph.md (Mermaid).
 * Usage: node tools/discover.ts <target>   (reads targets/<target>/spec/openapi.json)
 * Edges are heuristic (creator → consumer of a path id named after the same resource). Body-field and cross-resource
 * dependencies (e.g. cart_id in an invoice body) are invisible to it: put them in map/edges.manual.json
 * `{ "add": [{from,to,via}], "drop": [{from,to}] }`, which is merged on every run so regeneration never loses them.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

interface Op {
  id: string;
  method: string;
  path: string;
  tags: string[];
  security: string[];
  params: string[];
  requestBody: boolean;
  responses: string[];
}
interface Edge {
  from: string;
  to: string;
  via: string;
}

const target = process.argv[2];
if (!target) throw new Error('usage: node tools/discover.ts <target>');
const dir = join('targets', target);
const doc = JSON.parse(readFileSync(join(dir, 'spec', 'openapi.json'), 'utf8')) as {
  paths: Record<
    string,
    Record<
      string,
      {
        operationId?: string;
        tags?: string[];
        security?: Record<string, unknown>[];
        parameters?: { name: string; in: string }[];
        requestBody?: unknown;
        responses?: Record<string, unknown>;
      }
    >
  >;
};

const METHODS = ['get', 'post', 'put', 'patch', 'delete'];
const ops: Op[] = [];
for (const [path, item] of Object.entries(doc.paths)) {
  for (const [m, o] of Object.entries(item)) {
    if (!METHODS.includes(m)) continue;
    ops.push({
      id: o.operationId ?? `${m.toUpperCase()} ${path}`,
      method: m.toUpperCase(),
      path,
      tags: o.tags ?? [],
      security: (o.security ?? []).flatMap((s) => Object.keys(s)),
      params: (o.parameters ?? []).map((p) => `${p.in}:${p.name}`),
      requestBody: !!o.requestBody,
      responses: Object.keys(o.responses ?? {}),
    });
  }
}

const resource = (p: string) => p.split('/')[1] ?? '';
/** Drop `createCart → …/{productId}`: a param named after a *different* resource is that resource's id. */
const singular = (r: string) => r.replace(/s$/, '').replace(/-/g, '').toLowerCase();
const resources = new Set(ops.map((o) => singular(resource(o.path))));
const ownsParam = (res: string, param: string) => ![...resources].some((r) => r && r !== singular(res) && param.toLowerCase().startsWith(r));
let edges: Edge[] = [];
for (const consumer of ops) {
  const ids = [...consumer.path.matchAll(/\{(\w+)\}/g)].map((x) => x[1]!);
  for (const id of ids) {
    for (const creator of ops) {
      if (
        creator.method === 'POST' &&
        !creator.path.includes('{') &&
        resource(creator.path) === resource(consumer.path) &&
        ownsParam(resource(consumer.path), id) &&
        creator.id !== consumer.id
      ) {
        edges.push({ from: creator.id, to: consumer.id, via: id });
      }
    }
  }
}

const manualPath = join(dir, 'map', 'edges.manual.json');
if (existsSync(manualPath)) {
  const manual = JSON.parse(readFileSync(manualPath, 'utf8')) as { add?: Edge[]; drop?: Omit<Edge, 'via'>[] };
  edges = edges.filter((e) => !(manual.drop ?? []).some((d) => d.from === e.from && d.to === e.to)).concat(manual.add ?? []);
}

mkdirSync(join(dir, 'map'), { recursive: true });
writeFileSync(join(dir, 'map', 'catalog.json'), JSON.stringify({ target, generatedBy: 'tools/discover.ts', ops, edges }, null, 2) + '\n');
const safe = (s: string) => s.replace(/[^\w]/g, '_');
const mermaid = [
  '```mermaid',
  'flowchart LR',
  ...ops.map((o) => `  ${safe(o.id)}["${o.method} ${o.path}<br/>${o.id}"]`),
  ...edges.map((e) => `  ${safe(e.from)} -->|${e.via}| ${safe(e.to)}`),
  '```',
];
writeFileSync(
  join(dir, 'map', 'graph.md'),
  `# ${target} operation graph\n\nGenerated by \`node tools/discover.ts ${target}\`. Edges are heuristic — confirm or edit.\n\n${mermaid.join('\n')}\n`,
);
console.log(`${target}: ${ops.length} ops, ${edges.length} edges → ${join(dir, 'map')}`);
