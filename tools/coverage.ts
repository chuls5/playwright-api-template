/**
 * Coverage report: catalog ops × levels reached, from test tags.
 * Usage: node tools/coverage.ts [target...]   (default: every target with map/catalog.json)
 * Level comes from the spec file name (*.L<n>.spec.ts); ops from `@api:<id>` tags in that file.
 * Writes targets/<t>/map/coverage.json + coverage.md (table + Mermaid coloured by highest level).
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const walk = (d: string): string[] => readdirSync(d).flatMap((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : [join(d, f)]));
const targets = process.argv.slice(2).length
  ? process.argv.slice(2)
  : readdirSync('targets').filter((t) => existsSync(join('targets', t, 'map', 'catalog.json')));

for (const t of targets) {
  const dir = join('targets', t);
  const catalog = JSON.parse(readFileSync(join(dir, 'map', 'catalog.json'), 'utf8')) as { ops: { id: string }[] };
  const hits = new Map<string, Map<number, number>>(); // op → level → test count (approx: tags per file)
  for (const f of walk(join(dir, 'tests')).filter((x) => x.endsWith('.spec.ts'))) {
    const level = Number(/\.L(\d)\.spec\.ts$/.exec(f)?.[1] ?? NaN);
    if (Number.isNaN(level)) continue;
    const src = readFileSync(f, 'utf8');
    for (const m of src.matchAll(/@api:([\w.{}$-]+)/g)) {
      const id = m[1]!;
      const lv = hits.get(id) ?? new Map<number, number>();
      lv.set(level, (lv.get(level) ?? 0) + 1);
      hits.set(id, lv);
    }
  }
  const rows = catalog.ops.map((o) => {
    const lv = hits.get(o.id) ?? new Map<number, number>();
    const levels = [0, 1, 2, 3, 4].map((l) => lv.get(l) ?? 0);
    const max = levels.reduce((acc, n, i) => (n ? i : acc), -1);
    return { op: o.id, levels, max };
  });
  const covered = rows.filter((r) => r.max >= 1).length;
  writeFileSync(join(dir, 'map', 'coverage.json'), JSON.stringify({ target: t, ops: rows.length, coveredL1plus: covered, rows }, null, 2) + '\n');
  const safe = (s: string) => s.replace(/[^\w]/g, '_');
  const colour = ['#eee', '#cfe8ff', '#9fd0ff', '#6fb8ff', '#3fa0ff', '#0f88ff'];
  const md = [
    `# ${t} coverage`,
    '',
    `Generated by \`node tools/coverage.ts ${t}\`. ${covered}/${rows.length} ops have L1+ tests. Cells = tagged occurrences per level file (approximate).`,
    '',
    '| op | L0 | L1 | L2 | L3 | L4 |',
    '|---|---|---|---|---|---|',
    ...rows.map((r) => `| ${r.op} | ${r.levels.map((n) => (n ? String(n) : '·')).join(' | ')} |`),
    '',
    '```mermaid',
    'flowchart LR',
    ...rows.map((r) => `  ${safe(r.op)}["${r.op}<br/>${r.max < 0 ? 'none' : `L${r.max}`}"]`),
    ...rows.map((r) => `  style ${safe(r.op)} fill:${colour[r.max + 1]}`),
    '```',
    '',
  ];
  writeFileSync(join(dir, 'map', 'coverage.md'), md.join('\n'));
  console.log(`${t}: ${covered}/${rows.length} ops at L1+`);
}
